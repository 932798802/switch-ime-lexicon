# -*- coding: utf-8 -*-
"""gen_embed.py —— 把 assets/ 下的 NJDC 词典内嵌进 .nro。

生成两个文件（都在 source/ 下，会被 devkitPro 的 Makefile 自动编译）：
  embed.s        : 用 .incbin 把词典字节塞进 .rodata，导出 kMulti0 / kMulti0End 等符号
  embed_meta.h   : 每个包的 sha256 / 体积 / 目标文件名，供界面显示与自检

包的模型
--------
一个「包」= 要一起安装的一组词典文件（因为现在支持多本分担，
一个方案可能同时写 njubase1.a + njubase2.a + njubase3.a）。

    PACKS = [ (符号前缀, 人类可读名, [(目标文件名, 资产文件名), ...]), ... ]

符号命名：<前缀><序号>  与  <前缀><序号>End
    kMulti 包第 0 个文件 -> kMulti0 / kMulti0End

为什么自己写 .s 而不用 devkitPro 的 bin2s：
  bin2s 生成的符号名依赖输入路径，不可控；自己写 .incbin 符号名确定、可读、好排错。
  .incbin 的路径在这里写成**绝对路径**（正斜杠）——因为汇编器的当前工作目录是 build/，
  相对路径会找不到文件，这是 .incbin 最常见的坑。

用法：  python tools/gen_embed.py       （由 build.bat 自动调用）
"""
import hashlib
import os
import sys
import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                 # nro/
ASSETS = os.path.join(ROOT, "assets")
SRC = os.path.join(ROOT, "source")

# (符号前缀, 人类可读名, [(目标文件名, 资产文件名), ...])
PACKS = [
    ("kMulti", "MULTI 411k (base1+base2+base3)", [
        ("njubase1.a", "multi-njubase1.a"),
        ("njubase2.a", "multi-njubase2.a"),
        ("njubase3.a", "multi-njubase3.a"),
    ]),
    ("kFull", "ABBREV full (base3 only)", [
        ("njubase3.a", "njubase3.a"),
    ]),
    ("kLite", "LITE 80k (base3 only)", [
        ("njubase3.a", "njubase3-lite.a"),
    ]),
]


def asm_path(p):
    """转成汇编器能吃的绝对路径（正斜杠）。"""
    return p.replace("\\", "/")


def main():
    os.makedirs(SRC, exist_ok=True)

    lines = [
        "/* AUTO-GENERATED by tools/gen_embed.py - do not edit. */",
        '\t.section .rodata',
    ]
    meta = [
        "/* AUTO-GENERATED by tools/gen_embed.py - do not edit. */",
        "#pragma once",
        "",
    ]
    total = 0

    for sym, label, files in PACKS:
        up = sym.upper()
        present = []
        for idx, (target, fname) in enumerate(files):
            path = os.path.join(ASSETS, fname)
            vsym = "%s%d" % (sym, idx)
            if not os.path.isfile(path):
                print("!! 警告：缺少资产 %s —— 将嵌入 1 字节占位（功能不可用）" % fname)
                lines += [
                    "\t.balign 16",
                    "\t.global %s" % vsym,
                    "%s:" % vsym,
                    "\t.byte 0",
                    "\t.global %sEnd" % vsym,
                    "%sEnd:" % vsym,
                ]
                meta += ['#define DICT_%s_SIZE%d 0' % (up, idx),
                         '#define DICT_%s_SHA%d ""' % (up, idx)]
                present.append(0)
                continue

            data = open(path, "rb").read()
            digest = hashlib.sha256(data).hexdigest()
            total += len(data)
            print("  嵌入 %-20s %10d B  -> %-12s sha256=%s"
                  % (fname, len(data), target, digest[:16]))

            lines += [
                "\t.balign 16",
                "\t.global %s" % vsym,
                "%s:" % vsym,
                '\t.incbin "%s"' % asm_path(path),
                "\t.global %sEnd" % vsym,
                "%sEnd:" % vsym,
            ]
            meta += [
                '#define DICT_%s_TARGET%d "%s"' % (up, idx, target),
                '#define DICT_%s_SIZE%d %d' % (up, idx, len(data)),
                '#define DICT_%s_SHA%d "%s"' % (up, idx, digest),
            ]
            present.append(1)

        meta += [
            '#define DICT_%s_PRESENT %d' % (up, 1 if all(present) and present else 0),
            '#define DICT_%s_NFILES %d' % (up, len(files)),
            '#define DICT_%s_LABEL "%s"' % (up, label),
            "",
        ]

    lines.append("")

    with open(os.path.join(SRC, "embed.s"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))

    meta += [
        '#define DICT_GENERATED_AT "%s"' % datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "",
    ]
    with open(os.path.join(SRC, "embed_meta.h"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(meta) + "\n")

    print("完成：source/embed.s + source/embed_meta.h  合计内嵌 %.2f MB" % (total / 1048576.0))
    return 0


if __name__ == "__main__":
    sys.exit(main())
